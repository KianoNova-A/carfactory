    private boolean tacharInfoLinea1(String buscado) {
    //este metodo es llamado en los infoLineaXMousePressed para buscar por la info en el JTextPane y hacerle un tachado a la linea correcta
    StyledDocument doc = infoLinea1.getStyledDocument();
        try {
            String contenido = doc.getText(0, doc.getLength());
            SimpleAttributeSet estilo = new SimpleAttributeSet();
            StyleConstants.setStrikeThrough(estilo, true);

            int inicio = 0;
            while (inicio < contenido.length()) {
                int fin = contenido.indexOf('\n', inicio);
                if (fin < 0) fin = contenido.length();

                    String linea = contenido.substring(inicio, fin).trim();
                if (linea.equalsIgnoreCase(buscado)) {
                    doc.setCharacterAttributes(inicio, fin - inicio, estilo, false);
                    return true;
            }
            inicio = fin + 1;
        }
    } catch (BadLocationException e) {
        
    }
    return false;
}
    
